/** 正文末尾常见的元叙述行（整行丢弃）。 */
const TRAILING_NARRATION =
  /^(?:let me know|feel free|hope (?:this|that|it)|if you (?:need|have|want)|please (?:let me know|review)|如有(?:需要|问题|疑问)|希望(?:这|以上|对)|以上(?:就是|是|为))/iu;

// scheme 长度有界（RFC 3986 实际不会超过 32 字符）：避免 `[a-z0-9+.-]*` 在长文本上
// 吞掉整串再回溯（O(n²)，64 KiB 输入会跑出秒级甚至更久）。
const URL_TOKEN = /\b[a-z][a-z0-9+.-]{0,31}:\/\/[^\s"'`<>]+/giu;
const SECRET_TOKEN =
  /\b(?:gh[pousr]_[A-Za-z0-9]{16,}|github_pat_[A-Za-z0-9_]{20,}|glpat-[A-Za-z0-9_-]{16,}|sk-[A-Za-z0-9]{20,}|xox[baprs]-[A-Za-z0-9-]{10,})\b/gu;
const BEARER_TOKEN = /\b(Bearer)\s+[A-Za-z0-9._~+/=-]{8,}/giu;

/** 剥离文本中 URL 的内嵌凭据与令牌样式内容（幂等）。 */
function scrubSecrets(text: string): string {
  return text
    .replace(URL_TOKEN, (match) => sanitizeRemoteUrl(match))
    .replace(BEARER_TOKEN, '$1 ***')
    .replace(SECRET_TOKEN, '***');
}

function isCommitType(value: string): value is CommitType {
  return (COMMIT_TYPES as readonly string[]).includes(value);
}

function resolveType(raw: string): CommitType | null {
  const value = raw.toLowerCase();
  if (isCommitType(value)) return value;
  return TYPE_ALIASES[value] ?? null;
}

function stripOuterQuotes(text: string): string {
  let value = text.trim();
  const pairs: Readonly<Record<string, string>> = { '"': '"', "'": "'", '`': '`', '“': '”', '「': '」' };
  for (let round = 0; round < 3; round += 1) {
    if (value.length < 2) break;
    const first = value.charAt(0);
    const last = value.charAt(value.length - 1);
    if (pairs[first] !== last) break;
    value = value.slice(1, -1).trim();
  }
  return value;
}

/** 剥掉 `git commit -m "..."` / `git commit -am '...'` 包裹。 */
function unwrapGitCommit(text: string): string {
  // 短参数允许组合（`-am` / `-am`），捕获长度有界，避免在超长输入上回溯。
  const match = /^\s*git\s+commit\b[^"'\n]*?(?:-[A-Za-z]*m|--message)(?:\s+|=)(?:"([\s\S]{0,16384})"|'([\s\S]{0,16384})')\s*$/iu.exec(
    text,
  );
  if (match === null) return text;
  return match[1] ?? match[2] ?? '';
}

/** 剥掉 markdown 代码围栏：整行围栏删掉，行内 ``` 直接去掉。 */
function stripCodeFences(text: string): string {
  return text
    .split('\n')
    .map((line) => (/^\s*```[A-Za-z0-9_+.-]*\s*$/u.test(line) ? '' : line.replace(/```/gu, '')))
    .join('\n');
}

/** 剥掉开头的元叙述（"根据对话"、"Here is"、"This commit adds"…）。 */
function stripNarration(input: string): string {
  let value = input.trim();
  for (let round = 0; round < 8; round += 1) {
    const before = value;
    const verbMatch = EN_NARRATION_VERB.exec(value);
    if (verbMatch !== null) {
      const verb = (verbMatch[1] ?? '').toLowerCase();
      value = `${EN_IMPERATIVE[verb] ?? verb} ${value.slice(verbMatch[0].length)}`;
    } else {
      for (const pattern of NARRATION_PATTERNS) {
        if (pattern.test(value)) {
          value = value.replace(pattern, '');
          break;
        }
      }
    }
    value = value.replace(/^[\s:：,，。.;；\-—]+/u, '');
    if (value === before) break;
  }
  return value;
}

function stripLabel(line: string): string {
  return line.replace(/^\s*(?:subject|message|commit\s+message|title|提交信息|提交说明|提交消息|标题)\s*[:：]\s*/iu, '');
}

function stripListMarker(line: string): string {
  return line.replace(/^\s*(?:[-*•]|\d+[.)])\s+/u, '');
}

function isPunctuationOnly(line: string): boolean {
  return /^[\s:：,，。.;；\-—]+$/u.test(line);
}

/** 只有标签没有内容的首行（例如"改动："、"以下是提交信息："）。 */
function isLabelOnly(line: string): boolean {
  return /^[^\n:：]{1,24}[:：]$/u.test(line);
}

function cleanSubject(raw: string): string {
  let subject = stripOuterQuotes(raw).replace(/\s+/gu, ' ').trim();
  subject = stripListMarker(subject).trim();
  subject = subject.replace(/[.。]+$/u, '').trim();
  const firstWord = subject.split(' ')[0] ?? '';
  // 只把"首字母大写 + 其余小写"的普通词降为小写；保留 GitHub / API / Node.js 这类专名。
  if (/^[A-Z][a-z]+$/u.test(firstWord)) {
    subject = subject.charAt(0).toLowerCase() + subject.slice(1);
  }
  return truncateSubject(subject);
}

function truncateSubject(subject: string, maxLength = MAX_SUBJECT_LENGTH): string {
  const chars = Array.from(subject);
  if (chars.length <= maxLength) return subject;
  const cut = chars.slice(0, maxLength - 1).join('');
  const lastSpace = cut.lastIndexOf(' ');
  const base = lastSpace > maxLength / 2 ? cut.slice(0, lastSpace) : cut;
  const trimmed = base.replace(/[\s,;:.\-]+$/u, '');
  return `${trimmed === '' ? cut.trim() : trimmed}…`;
}

function wrapLine(line: string, maxLength = MAX_BODY_LINE_LENGTH): string[] {
  if (Array.from(line).length <= maxLength) return [line];
  const words = line.split(/\s+/u);
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    if (word === '') continue;
    const candidate = current === '' ? word : `${current} ${word}`;
    if (Array.from(candidate).length <= maxLength) {
      current = candidate;
      continue;
    }
    if (current !== '') {
      lines.push(current);
      current = '';
    }
    const wordChars = Array.from(word);
    if (wordChars.length <= maxLength) {
      current = word;
      continue;
    }
    for (let index = 0; index < wordChars.length; index += maxLength) {
      const chunk = wordChars.slice(index, index + maxLength).join('');
      if (index + maxLength >= wordChars.length) {
        current = chunk;
      } else {
        lines.push(chunk);
      }
    }
  }
  if (current !== '') lines.push(current);
  return lines.length === 0 ? [''] : lines;
}

interface ParsedHeader {
  readonly type: CommitType;
  readonly scope: string;
  readonly breaking: boolean;
  readonly subject: string;
}

function parseHeader(rawLine: string): ParsedHeader {
  const line = stripOuterQuotes(stripListMarker(stripLabel(rawLine)).trim()).trim();
  const match = /^([A-Za-z]+)(?:\(([^)]{0,64})\))?(!)?\s*[:：]\s*(.+)$/u.exec(line);
  if (match === null) {
    return { type: 'chore', scope: '', breaking: false, subject: cleanSubject(line) };
  }
  const rawType = (match[1] ?? '').toLowerCase();
  const resolved = resolveType(rawType);
  const rest = (match[4] ?? '').trim();
  // 未知 type（例如 `wip:`）统一归到 chore，并丢掉这个不合规的前缀。
  return {
    type: resolved ?? 'chore',
    scope: resolved === null ? '' : (match[2] ?? '').trim(),
    breaking: resolved === null ? false : match[3] === '!',
    subject: cleanSubject(rest === '' ? line : rest),
  };
}

function formatHeader(header: ParsedHeader): string {
  const scope = header.scope === '' ? '' : `(${header.scope})`;
  const breaking = header.breaking ? '!' : '';
  return `${header.type}${scope}${breaking}: ${header.subject}`;
}

/**
 * 清洗模型输出为一条可提交的信息。
 *
 * 保证：非空时首行一定是 `<type>(<scope>): <subject>`（type 在白名单内），
 * 正文与首行之间恰好一个空行；无有效内容时返回空串（由调用方回退）。
 */
export function sanitizeCommitMessage(raw: string): string {
  if (typeof raw !== 'string') return '';
  let text = raw.replace(/\r\n?/gu, '\n');
  text = unwrapGitCommit(text);
  text = stripCodeFences(text);
  text = stripOuterQuotes(text.trim());
  text = stripNarration(text);

  const lines = text.split('\n').map((line) => line.trimEnd());
  while (lines.length > 0) {
    const first = (lines[0] ?? '').trim();
    if (first === '' || isPunctuationOnly(first) || isLabelOnly(first)) {
      lines.shift();
      continue;
    }
    break;
  }
  if (lines.length === 0) return '';

  const header = parseHeader(lines[0] ?? '');
  if (header.subject === '') return '';

  const bodyLines = lines.slice(1);
  while (bodyLines.length > 0 && (bodyLines[0] ?? '').trim() === '') bodyLines.shift();

  const cleanedBody: string[] = [];
  for (let index = 0; index < bodyLines.length; index += 1) {
    const original = bodyLines[index] ?? '';
    const line = (index === 0 ? stripLabel(original) : original).trim();
    if (line === '') {
      cleanedBody.push('');
      continue;
    }
    if (TRAILING_NARRATION.test(line) || /^(?:-{3,}|\*{3,})$/u.test(line)) continue;
    cleanedBody.push(...wrapLine(line, MAX_BODY_LINE_LENGTH));
  }
  while (cleanedBody.length > 0 && (cleanedBody[cleanedBody.length - 1] ?? '').trim() === '') {
    cleanedBody.pop();
  }

  const firstLine = formatHeader(header);
  const body = cleanedBody.join('\n');
  const message = body === '' ? firstLine : `${firstLine}\n\n${body}`;
  return scrubSecrets(message).trim();
}

function cleanPath(path: string): string {
  return String(path)
    .replace(/\\/gu, '/')
    .replace(/^\.\//u, '')
    .replace(/[\0\r\n]/gu, ' ')
    .trim();
}

function inferFallbackType(paths: readonly string[]): CommitType {
  if (paths.length === 0) return 'chore';
  const every = (pattern: RegExp): boolean => paths.every((path) => pattern.test(path));
  if (every(/^\.github\/workflows\//u)) return 'ci';
  if (every(/\.(?:md|mdx|txt|rst|adoc)$/iu) || every(/^docs?\//iu)) return 'docs';
  if (every(/(?:^|\/)(?:tests?|__tests__|spec)\//u) || every(/\.(?:test|spec)\.[cm]?[jt]sx?$/iu)) return 'test';
  if (
    every(
      /^(?:package\.json|pnpm-lock\.yaml|pnpm-workspace\.yaml|tsconfig[^/]*\.json|esbuild\.config\.[^/]+|vitest\.config\.[^/]+|\.github\/)/u,
    )
  ) {
    return 'build';
  }
  return 'chore';
}

/**
 * 确定性兜底文案：模型不可用时界面仍能直接提交（用户可再编辑）。
 * 首行始终是合法的 Conventional Commit，subject ≤ 72 字符。
 */
export function fallbackCommitMessage(files: readonly string[]): string {
  const paths = files.map(cleanPath).filter((path) => path !== '');
  const type = inferFallbackType(paths);
  if (paths.length === 0) return scrubSecrets(`${type}: update files`);
  if (paths.length === 1) {
    return scrubSecrets(`${type}: ${truncateSubject(`update ${paths[0] ?? ''}`)}`);
  }
  return scrubSecrets(`${type}: update ${paths.length} files`);
}

/** 按 UTF-8 字节数截断文本（不把半个多字节字符留在末尾）。 */
function truncateText(text: string, maxBytes: number): { text: string; truncated: boolean } {
  const limit =
    Number.isFinite(maxBytes) && maxBytes > 0 ? Math.floor(maxBytes) : DEFAULT_COMMIT_MAX_DIFF_BYTES;
  const bytes = new TextEncoder().encode(text);
  if (bytes.length <= limit) return { text, truncated: false };
  const decoded = new TextDecoder('utf-8', { fatal: false }).decode(bytes.subarray(0, limit));
  return { text: decoded.replace(/\uFFFD+$/u, ''), truncated: true };
}

function buildCommitPromptInternal(
  input: CommitMessageInput,
  maxDiffBytes: number,
): { system: string; prompt: string; truncated: boolean } {
  const files = input.files.map((file) => file.trim()).filter((file) => file !== '');
  const rawDiff = typeof input.diff === 'string' ? input.diff : '';
  // 先剥离凭据再截断：避免截断点把 `https://user:token@` 切在中间导致脱敏失效。
  const truncatedDiff = truncateText(scrubSecrets(rawDiff), maxDiffBytes);
  const diffSection =
    truncatedDiff.text === ''
      ? '(no diff provided)'
      : truncatedDiff.truncated
        ? `${truncatedDiff.text}\n${TRUNCATION_MARKER}`
        : truncatedDiff.text;

  const sessionChanges = input.sessionChanges ?? [];
  const sections: string[] = [
    'Generate a Conventional Commits message for the following change.',
    `Changed files (${files.length}):\n${files.length === 0 ? '(none)' : files.map((file) => `- ${file}`).join('\n')}`,
  ];
  if (sessionChanges.length > 0) {
    const sessionLines = sessionChanges.map(
      (change) =>
        `- ${change.path} [${change.status}] +${change.added === null ? '?' : String(change.added)} -${
          change.removed === null ? '?' : String(change.removed)
        }`,
    );
    sections.push(`Session changes (context only; do not copy paths verbatim):\n${sessionLines.join('\n')}`);
  }
  const hint = (input.hint ?? '').trim();
  if (hint !== '') sections.push(`User hint:\n${hint}`);
  sections.push(`Diff${truncatedDiff.truncated ? ' (truncated)' : ''}:\n${diffSection}`);
  sections.push('Return only the commit message.');

  return {
    system: SYSTEM_PROMPT,
    prompt: scrubSecrets(sections.join('\n\n')),
    truncated: truncatedDiff.truncated,
  };
}

/**
 * 构造提示词（纯函数，便于单测）。
 *
 * diff 超过默认 {@link DEFAULT_COMMIT_MAX_DIFF_BYTES} 时截断，并在末尾标注
 * `… (diff truncated)`。服务实例自定义了 `maxDiffBytes` 时走内部版本。
 */
export function buildCommitPrompt(input: CommitMessageInput): { system: string; prompt: string } {
  const built = buildCommitPromptInternal(input, DEFAULT_COMMIT_MAX_DIFF_BYTES);
  return { system: built.system, prompt: built.prompt };
}

/**
 * 提交信息生成服务。
 *
 * `complete` 由 Host 注入（当前会话的 provider，一次性、无工具）。任何失败都
 * 以 `source='fallback'` + 非空 message 返回，**不抛错**。
 */
export class CommitMessageService {
  private readonly complete: CompletionFn;
  private readonly timeoutMs: number;
  private readonly maxDiffBytes: number;

  constructor(opts: CommitMessageServiceOptions) {
    this.complete = opts.complete;
    this.timeoutMs =
      opts.timeoutMs !== undefined && Number.isFinite(opts.timeoutMs) && opts.timeoutMs > 0
        ? Math.floor(opts.timeoutMs)
        : DEFAULT_COMMIT_TIMEOUT_MS;
    this.maxDiffBytes =
      opts.maxDiffBytes !== undefined && Number.isFinite(opts.maxDiffBytes) && opts.maxDiffBytes > 0
        ? Math.floor(opts.maxDiffBytes)
        : DEFAULT_COMMIT_MAX_DIFF_BYTES;
  }

  async generate(input: CommitMessageInput): Promise<CommitMessageResult> {
    try {
      return await this.run(input);
    } catch {
      return {
        message: fallbackCommitMessage(input.files),
        source: 'fallback',
        truncated: false,
        reason: FALLBACK_REASON_FAILED,
      };
    }
  }

  private async run(input: CommitMessageInput): Promise<CommitMessageResult> {
    const built = buildCommitPromptInternal(input, this.maxDiffBytes);
    const truncated = built.truncated;
    const controller = new AbortController();
    let timer: ReturnType<typeof setTimeout> | undefined;
    let timedOut = false;

    const timeout = new Promise<never>((_resolve, reject) => {
      timer = setTimeout(() => {
        timedOut = true;
        controller.abort();
        reject(new Error('commit message completion timed out'));
      }, this.timeoutMs);
    });

    try {
      const completion = Promise.resolve().then(() =>
        this.complete({ system: built.system, prompt: built.prompt, signal: controller.signal }),
      );
      const raw = await Promise.race([completion, timeout]);
      const message = sanitizeCommitMessage(typeof raw === 'string' ? raw : '');
      if (message === '') {
        return {
          message: fallbackCommitMessage(input.files),
          source: 'fallback',
          truncated,
          reason: FALLBACK_REASON_EMPTY,
        };
      }
      return { message, source: 'model', truncated, reason: null };
    } catch {
      return {
        message: fallbackCommitMessage(input.files),
        source: 'fallback',
        truncated,
        reason: timedOut ? FALLBACK_REASON_TIMED_OUT : FALLBACK_REASON_UNAVAILABLE,
      };
    } finally {
      if (timer !== undefined) clearTimeout(timer);
    }
  }
}
