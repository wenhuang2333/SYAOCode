/**
 * 提交信息生成服务（`27` §4.3 FR-N-026 / §10.5.2 的 Host 侧纯服务）。
 *
 * 设计要点：
 *  - **纯服务**：不建连接、不读盘；模型调用由 Host 注入的 `complete` 完成
 *    （带工具、有副作用的调用不属于这里）。
 *  - **绝不抛错**：模型不可用 / 超时 / 返回空 / 清洗后为空，一律回退到确定性的
 *    {@link fallbackCommitMessage}，让界面能继续手填。
 *  - **输出受限**：首行 Conventional Commits（type 白名单）、subject ≤ 72 字符、
 *    正文每行 ≤ 100 字符；元叙述、代码围栏、`git commit -m "..."` 包裹、外层引号
 *    全部剥离。
 *  - **安全**：diff 与最终 message 里的 URL 内嵌凭据先剥离（复用 `git-run.ts` 的
 *    `sanitizeRemoteUrl`），令牌样式内容替换为 `***`；提示词不展开 home 路径。
 *  - **有界**：`timeoutMs`（默认 20 s）用 `AbortController` 实现，超时先 `abort()`
 *    再回退；diff 按 `maxDiffBytes`（默认 64 KiB）截断并显式标注。
 */

import { sanitizeRemoteUrl } from './git-run.ts';

/** Conventional Commits 允许的 `type` 集合。 */
export const COMMIT_TYPES = [
  'feat',
  'fix',
  'refactor',
  'perf',
  'test',
  'docs',
  'build',
  'chore',
  'ci',
  'style',
  'revert',
] as const;

export type CommitType = (typeof COMMIT_TYPES)[number];

/** 默认补全超时（`27` §4.3：生成失败可手填，不允许无限等待）。 */
export const DEFAULT_COMMIT_TIMEOUT_MS = 20_000;

/** 默认 diff 上限：64 KiB。 */
export const DEFAULT_COMMIT_MAX_DIFF_BYTES = 64 * 1024;

const MAX_SUBJECT_LENGTH = 72;
const MAX_BODY_LINE_LENGTH = 100;
const TRUNCATION_MARKER = '… (diff truncated)';

/** fallback 原因文案：固定、简短、无敏感信息（界面直接展示）。 */
const FALLBACK_REASON_UNAVAILABLE = 'model unavailable';
const FALLBACK_REASON_TIMED_OUT = 'model timed out';
const FALLBACK_REASON_EMPTY = 'model returned an empty message';
const FALLBACK_REASON_FAILED = 'commit message generation failed';

export interface CommitMessageInput {
  readonly workspaceRoot: string;
  /** 变更文件相对路径（用于兜底与提示词）。 */
  readonly files: readonly string[];
  /** 已暂存/待提交的 unified diff 文本；服务内部按 maxDiffBytes 截断。 */
  readonly diff: string;
  /** 可选：本会话改动（FileChange[]，来自 @syaocode/dhp），用于提示词补充意图。 */
  readonly sessionChanges?: readonly {
    readonly path: string;
    readonly status: string;
    readonly added: number | null;
    readonly removed: number | null;
  }[];
  /** 可选：用户补充说明（例如"这次只提交 Git 相关"）。 */
  readonly hint?: string;
}

export interface CompletionRequest {
  readonly system: string;
  readonly prompt: string;
  readonly signal: AbortSignal;
}

/** 一次性补全：由 Host 用当前会话的 provider 实现；不得带工具、不得有副作用。 */
export type CompletionFn = (req: CompletionRequest) => Promise<string>;

export interface CommitMessageResult {
  /** 最终提交信息（已清洗、已限制长度）。**保证非空**。 */
  readonly message: string;
  readonly source: 'model' | 'fallback';
  readonly truncated: boolean;
  /** source='fallback' 时给界面看的原因（简短、无敏感信息）。 */
  readonly reason: string | null;
}

export interface CommitMessageServiceOptions {
  readonly complete: CompletionFn;
  readonly timeoutMs?: number;
  readonly maxDiffBytes?: number;
}

